    /** Every country, for the admin list */
    public static function list(): array
    {
        return collect(self::ALL)->map(fn ($v, $code) => ['code' => $code, 'name' => $v[0], 'lite' => $v[1], 'blocked' => in_array($code, self::BLOCKED, true)])->values()->all();
    }

    /** The countries turned on in Admin Settings (always includes the US) */
    public static function enabled(): array
    {
        $on = \App\Services\Checks\Kyb::settings()['countries'] ?? ['US'];
        return array_values(array_unique(array_merge(['US'], array_filter($on, fn ($c) => isset(self::ALL[$c]) && !in_array($c, self::BLOCKED, true)))));
    }

    public static function isEnabled(?string $code): bool
    {
        return in_array(strtoupper((string) ($code ?: 'US')), self::enabled(), true);
    }
